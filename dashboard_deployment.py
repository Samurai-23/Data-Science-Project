CLASS_NAMES = ["Tumour", "Stroke", "Normal"]

def predict_ensemble(image):

    # Prepare the MRI image
    processed_image = preprocess_mri_image(image)

    # Get predictions from both models
    densenet_prediction = densenet_model.predict(
        processed_image, verbose=0
    )

    efficientnet_prediction = efficientnet_model.predict(
        processed_image, verbose=0
    )

    # Combine predictions using soft voting
    ensemble_prediction = (
        densenet_prediction + efficientnet_prediction
    ) / 2

    # Identify the predicted class
    predicted_index = np.argmax(ensemble_prediction[0])

    predicted_class = CLASS_NAMES[predicted_index]

    confidence = float(
        ensemble_prediction[0][predicted_index] * 100
    )

    # Prepare probability results
    probabilities = {
        CLASS_NAMES[i]: float(ensemble_prediction[0][i] * 100)
        for i in range(len(CLASS_NAMES))
    }

    return predicted_class, confidence, probabilities


